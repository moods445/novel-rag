#!/usr/bin/env bash
#
# 一键部署 novel-rag（Docker Compose）。
# 镜像只在 GitHub Actions 里构建并推到 ghcr.io，这个脚本只 pull，不 build。
#
# **单文件部署**：只要有 deploy.sh 就能跑，docker-compose.yml 由脚本按参数现生成。
#
# 用法：
#   ./deploy.sh                          拉最新镜像、后台启动、等健康检查通过
#   ./deploy.sh --port 9000              换宿主端口
#   ./deploy.sh --auth                   开启鉴权（没给 --token 就随机生成并打印）
#   ./deploy.sh --token mypass --auth    指定口令，访问用 /#token=mypass
#   ./deploy.sh --data /srv/novel-rag    换数据目录（默认 ./data，就在脚本旁边）
#   ./deploy.sh --embed hash             跳过 100MB 向量模型下载，最省资源
#   ./deploy.sh status | logs | restart | down | purge
#
# 执行后会在脚本同目录生成：
#   .env                 参数（下次直接 ./deploy.sh 就沿用，改了参数会覆盖）
#   docker-compose.yml   由脚本生成，手改会被下次执行覆盖
#   data/                数据目录（数据库、日志、embedding 模型；删容器不丢）
set -euo pipefail

cd "$(dirname "$0")"

COMPOSE_FILE="docker-compose.yml"
ENV_FILE=".env"
SERVICE="novel-rag"
DEFAULT_IMAGE="ghcr.io/moods445/novel-rag:latest"
DEFAULT_DATA="./data"          # 默认就落在脚本旁边

# ---------------------------------------------------------------- 输出
info() { printf '%s\n' "$*"; }
step() { printf '\n==> %s\n' "$*"; }
warn() { printf '警告: %s\n' "$*" >&2; }
die() { printf '错误: %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<'EOF'
用法: ./deploy.sh [动作] [选项]

动作（默认 up）:
  up         拉取镜像并后台启动，等健康检查通过（默认）
  restart    重启容器
  status     看容器与健康状态
  logs       跟随日志（Ctrl-C 退出）
  down       停止并删除容器（数据卷保留）
  purge      停止并删除容器 + 数据卷

选项:
  -p, --port N       宿主端口，默认 8000
  -t, --token S      访问口令（隐含开启鉴权）
      --auth         开启鉴权；没给 --token 会随机生成并打印
      --no-auth      关闭鉴权（默认，仅限内网/反代后面）
  -d, --data PATH    数据目录，默认 ./data（脚本旁边）；给普通的词则当命名卷
      --embed MODE   向量检索：auto（默认）/ hash（最省资源）/ bge
      --image IMG    换镜像地址，默认 ghcr.io/moods445/novel-rag:latest
      --query-base-url URL   问答模型地址（OpenAI 兼容，如 https://api.openai.com/v1）
      --query-api-key KEY    问答模型 API Key
      --query-model NAME     问答模型名（如 gpt-4o-mini）
      --extract-base-url URL 抽取模型地址（不填则复用 --query-* 的值）
      --extract-api-key KEY  抽取模型 API Key
      --extract-model NAME   抽取模型名
  -h, --help         显示这段帮助

说明:
  模型也可以启动后在设置页「添加 provider」里填（存容器内 /data 数据库，重启不丢）。
  不配置 --query-* 且没在设置页添加时，问答只会返回原文摘录
  （页面会提示「问答模型未配置」）。这些值也会写进 .env，下次直接沿用。

例子:
  ./deploy.sh                       # 内网直接跑起来，数据落在 ./data
  ./deploy.sh --auth --port 9000    # 开鉴权 + 换端口
  ./deploy.sh --data /srv/nr        # 数据换个地方
  ./deploy.sh --query-base-url https://api.openai.com/v1 \
              --query-api-key sk-xxx --query-model gpt-4o-mini

生成物（都在脚本同目录）:
  docker-compose.yml   每次执行按参数重写，改它没用
  .env                 参数，下次沿用
  data/                数据目录（默认）
EOF
}

# ---------------------------------------------------------------- 参数
ACTION="up"
arg_port=""
arg_token=""
arg_auth=""          # 1 = 开启鉴权 / 0 = 免鉴权 / 空 = 沿用 .env
arg_data=""
arg_embed=""
arg_image=""
arg_query_base_url=""
arg_query_api_key=""
arg_query_model=""
arg_extract_base_url=""
arg_extract_api_key=""
arg_extract_model=""

while [ $# -gt 0 ]; do
  case "$1" in
    up|down|restart|logs|status|purge) ACTION="$1"; shift ;;
    -p|--port)  arg_port="${2:-}";  shift 2 ;;
    -t|--token) arg_token="${2:-}"; arg_auth=1; shift 2 ;;
    --auth)     arg_auth=1; shift ;;
    --no-auth)  arg_auth=0; shift ;;
    -d|--data)  arg_data="${2:-}"; shift 2 ;;
    --embed)    arg_embed="${2:-}"; shift 2 ;;
    --image)    arg_image="${2:-}"; shift 2 ;;
    --query-base-url)    arg_query_base_url="${2:-}"; shift 2 ;;
    --query-api-key)     arg_query_api_key="${2:-}"; shift 2 ;;
    --query-model)       arg_query_model="${2:-}"; shift 2 ;;
    --extract-base-url)  arg_extract_base_url="${2:-}"; shift 2 ;;
    --extract-api-key)   arg_extract_api_key="${2:-}"; shift 2 ;;
    --extract-model)     arg_extract_model="${2:-}"; shift 2 ;;
    -h|--help)  usage; exit 0 ;;
    *) die "不认识的参数：$1（--help 看用法）" ;;
  esac
done

# ---------------------------------------------------------------- 环境自检
command -v docker >/dev/null 2>&1 || die "没装 docker"
docker info >/dev/null 2>&1 || die "docker 守护进程没起来（或当前用户没有权限）"
[ -w . ] || die "当前目录不可写，没法生成 $COMPOSE_FILE（把 deploy.sh 放到可写目录里跑）"

if docker compose version >/dev/null 2>&1; then
  compose() { docker compose "$@"; }
elif command -v docker-compose >/dev/null 2>&1; then
  compose() { docker-compose "$@"; }
else
  die "缺少 docker compose（v2 或 docker-compose 都行）"
fi

# 单文件部署：compose 文件由脚本现生成，不依赖仓库里有没有
COMPOSE_MARKER="# generated by deploy.sh"
write_compose() {
  if [ -f "$COMPOSE_FILE" ] && ! grep -qF "$COMPOSE_MARKER" "$COMPOSE_FILE"; then
    cp "$COMPOSE_FILE" "$COMPOSE_FILE.bak"
    warn "$COMPOSE_FILE 不是本脚本生成的，已备份成 $COMPOSE_FILE.bak 后覆盖"
  fi
  cat > "$COMPOSE_FILE" <<'YAML'
# generated by deploy.sh —— 本文件由 deploy.sh 生成，每次执行都会覆盖；要改请改脚本参数
#
# 手动用也行：docker compose pull && docker compose up -d
#
# 参数走同目录 .env：
#   NOVEL_RAG_PORT=8000           宿主端口
#   NOVEL_RAG_TOKEN=              设置后开启鉴权（访问用 /#token=xxx）
#   NOVEL_RAG_DISABLE_AUTH=1      1 = 不校验 token（内网/反代后面才用）
#   NOVEL_RAG_DATA=./data         数据目录，默认在脚本旁边；填普通名字则用命名卷
#   NOVEL_RAG_EMBED_BACKEND=auto  auto | hash
#
# 问答/抽取模型（不配置则问答只能做原文摘录）：
#   NOVEL_RAG_QUERY_BASE_URL / _API_KEY / _MODEL     问答模型（OpenAI 兼容）
#   NOVEL_RAG_EXTRACT_BASE_URL / _API_KEY / _MODEL   抽取模型
services:
  novel-rag:
    image: ${NOVEL_RAG_IMAGE:-ghcr.io/moods445/novel-rag:latest}
    container_name: ${NOVEL_RAG_CONTAINER:-novel-rag}
    restart: unless-stopped
    ports:
      - "${NOVEL_RAG_PORT:-8000}:8000"
    environment:
      NOVEL_RAG_DISABLE_AUTH: "${NOVEL_RAG_DISABLE_AUTH:-1}"
      NOVEL_RAG_TOKEN: "${NOVEL_RAG_TOKEN:-}"
      NOVEL_RAG_EMBED_BACKEND: "${NOVEL_RAG_EMBED_BACKEND:-auto}"
      # 模型调用（也可以在设置页「添加 provider」，存容器内 /data 的数据库，效果一样）
      NOVEL_RAG_QUERY_BASE_URL: "${NOVEL_RAG_QUERY_BASE_URL:-}"
      NOVEL_RAG_QUERY_API_KEY: "${NOVEL_RAG_QUERY_API_KEY:-}"
      NOVEL_RAG_QUERY_MODEL: "${NOVEL_RAG_QUERY_MODEL:-}"
      NOVEL_RAG_EXTRACT_BASE_URL: "${NOVEL_RAG_EXTRACT_BASE_URL:-}"
      NOVEL_RAG_EXTRACT_API_KEY: "${NOVEL_RAG_EXTRACT_API_KEY:-}"
      NOVEL_RAG_EXTRACT_MODEL: "${NOVEL_RAG_EXTRACT_MODEL:-}"
      NOVEL_RAG_LLM_TIMEOUT: "${NOVEL_RAG_LLM_TIMEOUT:-240}"
      NOVEL_RAG_LLM_TIMEOUT_QUERY: "${NOVEL_RAG_LLM_TIMEOUT_QUERY:-120}"
      NOVEL_RAG_PROXY: "${NOVEL_RAG_PROXY:-}"
      NOVEL_RAG_LOG_LEVEL: "${NOVEL_RAG_LOG_LEVEL:-INFO}"
      TZ: "${TZ:-Asia/Shanghai}"
    volumes:
      # 数据库、日志、embedding 模型都在 /data，删容器不丢数据
      - "${NOVEL_RAG_DATA:-./data}:/data"

volumes:
  novel-rag-data:
YAML
}

# 纪律：镜像一律来自 CI，禁止本地构建
if grep -qE '^[[:space:]]*build:' "$COMPOSE_FILE" 2>/dev/null; then
  die "$COMPOSE_FILE 里出现了 build:，本项目禁止本地构建镜像"
fi

env_get() { # key -> .env 里的值（没有就空）
  [ -f "$ENV_FILE" ] || return 0
  sed -n "s/^$1=//p" "$ENV_FILE" | head -n1 | sed -e 's/^"//' -e 's/"$//'
}

gen_token() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 12
  else
    od -An -tx1 -N12 /dev/urandom | tr -d ' \n'
  fi
}

# 容器内以非 root（uid 10001）运行，bind mount 的目录得让它写得进去
ensure_data_writable() {
  local dir="$1"
  if [ "$(id -u)" = "0" ]; then
    chown -R 10001:10001 "$dir" 2>/dev/null || true
  elif command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then
    sudo -n chown -R 10001:10001 "$dir" 2>/dev/null || true
  fi
  # 既不是 10001 的、也没有 others write 才放宽（自建数据目录，代价可控）
  if [ -z "$(find "$dir" -maxdepth 0 \( -perm -o+w -o -uid 10001 \) 2>/dev/null)" ]; then
    chmod -R a+rwX "$dir" 2>/dev/null || true
    info "已把 $dir 放宽到容器内的 uid 10001 可写"
  fi
}

# 参数 > .env > 默认值
PORT="${arg_port:-$(env_get NOVEL_RAG_PORT)}";             PORT="${PORT:-8000}"
TOKEN="${arg_token:-$(env_get NOVEL_RAG_TOKEN)}"
DATA="${arg_data:-$(env_get NOVEL_RAG_DATA)}";             DATA="${DATA:-$DEFAULT_DATA}"
EMBED="${arg_embed:-$(env_get NOVEL_RAG_EMBED_BACKEND)}";  EMBED="${EMBED:-auto}"
IMAGE="${arg_image:-$(env_get NOVEL_RAG_IMAGE)}";          IMAGE="${IMAGE:-$DEFAULT_IMAGE}"
QUERY_BASE_URL="${arg_query_base_url:-$(env_get NOVEL_RAG_QUERY_BASE_URL)}"
QUERY_API_KEY="${arg_query_api_key:-$(env_get NOVEL_RAG_QUERY_API_KEY)}"
QUERY_MODEL="${arg_query_model:-$(env_get NOVEL_RAG_QUERY_MODEL)}"
# 抽取不单独配置时复用问答模型（同一个 OpenAI 兼容端点最常见）
EXTRACT_BASE_URL="${arg_extract_base_url:-$(env_get NOVEL_RAG_EXTRACT_BASE_URL)}"
EXTRACT_API_KEY="${arg_extract_api_key:-$(env_get NOVEL_RAG_EXTRACT_API_KEY)}"
EXTRACT_MODEL="${arg_extract_model:-$(env_get NOVEL_RAG_EXTRACT_MODEL)}"
EXTRACT_BASE_URL="${EXTRACT_BASE_URL:-$QUERY_BASE_URL}"
EXTRACT_API_KEY="${EXTRACT_API_KEY:-$QUERY_API_KEY}"
EXTRACT_MODEL="${EXTRACT_MODEL:-$QUERY_MODEL}"

case "$arg_auth" in
  1) DISABLE_AUTH=0 ;;
  0) DISABLE_AUTH=1 ;;
  *) DISABLE_AUTH="$(env_get NOVEL_RAG_DISABLE_AUTH)"; DISABLE_AUTH="${DISABLE_AUTH:-1}" ;;
esac

case "$PORT" in
  ''|*[!0-9]*) die "端口必须是数字：$PORT" ;;
esac
if [ "$PORT" -lt 1 ] || [ "$PORT" -gt 65535 ]; then
  die "端口超出范围：$PORT"
fi

case "$EMBED" in
  auto|hash|bge) ;;
  *) die "--embed 只能是 auto | hash | bge" ;;
esac

if [ "$DISABLE_AUTH" = "0" ] && [ -z "$TOKEN" ]; then
  TOKEN="$(gen_token)"
  [ -n "$TOKEN" ] || die "生成随机口令失败，请用 --token 指定"
  info "已生成访问口令：$TOKEN"
fi

# 数据目录：默认 ./data（脚本旁边）。bind mount 要提前建好并让容器内 uid 10001 能写
case "$DATA" in
  "~"*) DATA="${HOME}${DATA#\~}" ;;
esac
case "$DATA" in
  /*|.*|*/*)
    case "$DATA" in
      /*) DATA_ABS="$DATA" ;;
      *)  DATA_ABS="$(pwd)/${DATA#./}" ;;
    esac
    mkdir -p "$DATA_ABS" || die "建不了数据目录：$DATA_ABS"
    ensure_data_writable "$DATA_ABS"
    DATA="$DATA_ABS"
    ;;
  *)
    warn "--data $DATA 当命名卷处理，数据不在脚本目录；想落在本地就 --data ./data"
    ;;
esac

write_env() {
  # 保留用户手工加进 .env 的其它变量（代理、超时、自定义 provider 等），
  # 否则每次 ./deploy.sh 都会把它们清掉。
  local extras=""
  if [ -f "$ENV_FILE" ]; then
    extras="$(grep -Ev '^(NOVEL_RAG_(IMAGE|PORT|DATA|DISABLE_AUTH|TOKEN|EMBED_BACKEND|QUERY_BASE_URL|QUERY_API_KEY|QUERY_MODEL|EXTRACT_BASE_URL|EXTRACT_API_KEY|EXTRACT_MODEL)=|#)' "$ENV_FILE" || true)"
  fi
  umask 077
  cat > "$ENV_FILE" <<EOF
# 由 deploy.sh 生成；改这里等价于改 deploy.sh 的参数
NOVEL_RAG_IMAGE=$IMAGE
NOVEL_RAG_PORT=$PORT
NOVEL_RAG_DATA=$DATA
NOVEL_RAG_DISABLE_AUTH=$DISABLE_AUTH
NOVEL_RAG_TOKEN=$TOKEN
NOVEL_RAG_EMBED_BACKEND=$EMBED
NOVEL_RAG_QUERY_BASE_URL=$QUERY_BASE_URL
NOVEL_RAG_QUERY_API_KEY=$QUERY_API_KEY
NOVEL_RAG_QUERY_MODEL=$QUERY_MODEL
NOVEL_RAG_EXTRACT_BASE_URL=$EXTRACT_BASE_URL
NOVEL_RAG_EXTRACT_API_KEY=$EXTRACT_API_KEY
NOVEL_RAG_EXTRACT_MODEL=$EXTRACT_MODEL
EOF
  if [ -n "$extras" ]; then
    printf '%s\n' "$extras" >> "$ENV_FILE"
  fi
  umask 022
}

# shell 里残留的同名变量会盖掉 .env，交给 compose 之前先清掉
clear_env() {
  unset NOVEL_RAG_IMAGE NOVEL_RAG_PORT NOVEL_RAG_DATA \
        NOVEL_RAG_DISABLE_AUTH NOVEL_RAG_TOKEN NOVEL_RAG_EMBED_BACKEND \
        NOVEL_RAG_QUERY_BASE_URL NOVEL_RAG_QUERY_API_KEY NOVEL_RAG_QUERY_MODEL \
        NOVEL_RAG_EXTRACT_BASE_URL NOVEL_RAG_EXTRACT_API_KEY NOVEL_RAG_EXTRACT_MODEL \
        NOVEL_RAG_CONTAINER 2>/dev/null || true
}

lan_ip() {
  hostname -I 2>/dev/null | awk '{print $1}'
}

print_url() {
  local ip
  ip="$(lan_ip || true)"
  info ""
  info "访问地址："
  if [ "$DISABLE_AUTH" = "0" ]; then
    info "  本机   http://127.0.0.1:$PORT/#token=$TOKEN"
    if [ -n "$ip" ]; then info "  局域网 http://$ip:$PORT/#token=$TOKEN"; fi
  else
    info "  本机   http://127.0.0.1:$PORT/"
    if [ -n "$ip" ]; then info "  局域网 http://$ip:$PORT/"; fi
    info ""
    info "（当前免鉴权，只适合内网或反代后面；要口令就 ./deploy.sh --auth）"
  fi
  info ""
  if [ -z "$QUERY_MODEL" ] || [ -z "$QUERY_BASE_URL" ]; then
    warn "问答模型未配置：问答只会返回原文摘录。建议重新执行并带上 --query-base-url / --query-model / --query-api-key"
  else
    info "问答模型：$QUERY_MODEL @ $QUERY_BASE_URL"
  fi
  info "数据：$DATA"
  info "日志：./deploy.sh logs（容器内文件：$DATA/logs/backend.log）"
  info "停止：./deploy.sh down"
}

wait_healthy() {
  local cid status i
  cid="$(compose ps -q "$SERVICE" 2>/dev/null || true)"
  if [ -z "$cid" ]; then
    compose logs --tail 40 "$SERVICE" || true
    die "容器没起来"
  fi

  status="unknown"
  for i in $(seq 1 45); do
    status="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid" 2>/dev/null || echo unknown)"
    case "$status" in
      healthy)
        info "健康检查通过"
        return 0
        ;;
      exited|dead)
        break
        ;;
      running)
        # 没有 HEALTHCHECK 的镜像：跑起来几秒就当成功
        if [ "$i" -ge 3 ]; then
          info "容器已运行"
          return 0
        fi
        ;;
    esac
    sleep 2
  done

  warn "容器 90s 内没有变成 healthy（当前：$status）"
  compose logs --tail 40 "$SERVICE" || true
  die "启动失败"
}

do_up() {
  step "拉取镜像 $IMAGE（只 pull，不 build）"
  if ! compose pull "$SERVICE"; then
    die "拉镜像失败；仓库是私有包的话先登录：docker login ghcr.io -u <用户名>"
  fi

  step "启动容器"
  compose up -d --remove-orphans

  step "等待健康检查"
  wait_healthy

  print_url
}

clear_env

# 所有动作都先落地 compose 文件：单文件部署的前提
write_compose

case "$ACTION" in
  up)
    write_env
    do_up
    ;;
  restart)
    write_env
    step "重启容器"
    compose restart "$SERVICE"
    wait_healthy
    print_url
    ;;
  status)
    compose ps
    cid="$(compose ps -q "$SERVICE" 2>/dev/null || true)"
    if [ -n "$cid" ]; then
      info ""
      info "health: $(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid" 2>/dev/null || echo unknown)"
    fi
    ;;
  logs)
    compose logs -f --tail 200 "$SERVICE"
    ;;
  down)
    step "停止并删除容器（数据卷保留）"
    compose down
    info "数据还在：$DATA"
    info "要连数据一起删：./deploy.sh purge"
    ;;
  purge)
    step "停止、删除容器并删除数据卷"
    compose down -v
    case "$DATA" in
      /*) info "bind mount 目录不会自动删，需要的话手动 rm -rf $DATA" ;;
      *)  info "数据卷已删除：$DATA" ;;
    esac
    ;;
esac
